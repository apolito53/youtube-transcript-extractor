const form = document.getElementById("extract-form");
const urlInput = document.getElementById("url");
const languageInput = document.getElementById("language");
const timestampsInput = document.getElementById("include-timestamps");
const refreshInput = document.getElementById("refresh-cache");
const statusElement = document.getElementById("status");
const detailsElement = document.getElementById("details");
const outputCard = document.getElementById("output-card");
const outputElement = document.getElementById("output");
const warningsElement = document.getElementById("warnings");
const cleanTab = document.getElementById("clean-tab");
const formattedTab = document.getElementById("formatted-tab");
const copyButton = document.getElementById("copy-button");
const downloadButton = document.getElementById("download-button");
const versionChip = document.getElementById("version-chip");
const cacheChip = document.getElementById("cache-chip");

let cleanMarkdown = "";
let formattedMarkdown = "";
let activeOutput = "clean";
let videoTitle = "youtube-transcript";
let analysisVersion = 1;

function setStatus(message, kind) {
  statusElement.textContent = message || "";
  statusElement.className = "status" + (kind ? " " + kind : "");
}

function showWarnings(warnings) {
  warningsElement.replaceChildren();
  if (!warnings || warnings.length === 0) {
    warningsElement.hidden = true;
    return;
  }
  warnings.forEach((warning) => {
    const paragraph = document.createElement("p");
    paragraph.textContent = warning;
    warningsElement.appendChild(paragraph);
  });
  warningsElement.hidden = false;
}

function setActiveTab(tab) {
  activeOutput = tab;
  cleanTab.classList.toggle("active", tab === "clean");
  formattedTab.classList.toggle("active", tab === "formatted");
  outputElement.textContent = tab === "formatted" ? formattedMarkdown : cleanMarkdown;
}

function filename() {
  const safe = videoTitle
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 80);
  return (safe || "youtube-transcript") + "-v" + analysisVersion + ".md";
}

function errorMessage(error) {
  if (error && error.detail) {
    if (typeof error.detail === "string") return error.detail;
    if (error.detail.message) return error.detail.message;
  }
  return "Something went wrong. The transcript gremlin declined to elaborate.";
}

async function readJson(response) {
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(errorMessage(payload));
  return payload;
}

function formatAnalysisDate(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return String(value || "").slice(0, 10);
  return new Intl.DateTimeFormat(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
  }).format(date);
}

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const url = urlInput.value.trim();
  const language = languageInput.value.trim();
  const includeTimestamps = timestampsInput.checked;
  const refresh = refreshInput.checked;
  if (!url) return;

  form.querySelector("button[type=submit]").disabled = true;
  outputCard.hidden = true;
  detailsElement.hidden = true;
  setStatus(
    refresh
      ? "Refreshing captions and creating a new version…"
      : "Checking the cache, then fetching captions if needed…"
  );

  try {
    const extractResponse = await fetch("/api/extract", {
      method: "POST",
      headers: {"Content-Type": "application/json"},
      body: JSON.stringify({
        url,
        language: language || null,
        include_timestamps: includeTimestamps,
        refresh,
      }),
    });
    const extracted = await readJson(extractResponse);
    cleanMarkdown = extracted.clean_markdown;
    formattedMarkdown = "";
    activeOutput = "clean";
    setActiveTab("clean");
    showWarnings(extracted.warnings);

    const transcript = extracted.transcript;
    videoTitle = transcript.title || "youtube-transcript";
    document.getElementById("video-title").textContent =
      transcript.title || "YouTube transcript";
    document.getElementById("video-author").textContent =
      transcript.author ? "by " + transcript.author : "";
    document.getElementById("language-chip").textContent =
      transcript.language_name + " (" + transcript.language_code + ")";
    document.getElementById("caption-chip").textContent =
      transcript.is_generated ? "autogenerated captions" : "manual captions";
    const analysis = extracted.analysis;
    analysisVersion = analysis.version;
    versionChip.textContent =
      "v" + analysis.version + " · " + formatAnalysisDate(analysis.analyzed_at);
    if (analysis.transcript_from_cache) {
      cacheChip.textContent = "cached";
      cacheChip.hidden = false;
    } else if (refresh && analysis.version > 1) {
      cacheChip.textContent = "refreshed";
      cacheChip.hidden = false;
    } else {
      cacheChip.hidden = true;
    }
    detailsElement.hidden = false;
    outputCard.hidden = false;
    refreshInput.checked = false;

    if (extracted.formatting_available && extracted.formatted_markdown) {
      formattedMarkdown = extracted.formatted_markdown;
      formattedTab.disabled = false;
      setActiveTab("formatted");
      if (analysis.transcript_from_cache && analysis.formatted_from_cache) {
        setStatus("Loaded v" + analysis.version + " from the local cache.", "success");
      } else if (refresh && analysis.version > 1) {
        setStatus("Refreshed and saved v" + analysis.version + ".", "success");
      } else if (analysis.transcript_from_cache) {
        setStatus(
          "Loaded v" + analysis.version + " captions from cache and formatted this view.",
          "success"
        );
      } else {
        setStatus("Done. Your formatted transcript is cached as v1.", "success");
      }
    } else {
      formattedTab.disabled = true;
      setActiveTab("clean");
      setStatus(
        "Clean transcript v" + analysis.version + " ready. " +
          (extracted.formatting_message || "AI formatting was unavailable."),
        "success"
      );
    }
  } catch (error) {
    outputCard.hidden = true;
    setStatus(error.message || "The request failed.", "error");
  } finally {
    form.querySelector("button[type=submit]").disabled = false;
  }
});

cleanTab.addEventListener("click", () => setActiveTab("clean"));
formattedTab.addEventListener("click", () => {
  if (!formattedTab.disabled) setActiveTab("formatted");
});

copyButton.addEventListener("click", async () => {
  const text = activeOutput === "formatted" ? formattedMarkdown : cleanMarkdown;
  if (!text) return;
  try {
    await navigator.clipboard.writeText(text);
    setStatus("Copied Markdown to the clipboard.", "success");
  } catch {
    setStatus("Clipboard access was blocked; select the text and copy it manually.", "error");
  }
});

downloadButton.addEventListener("click", () => {
  const text = activeOutput === "formatted" ? formattedMarkdown : cleanMarkdown;
  if (!text) return;
  const blob = new Blob([text], {type: "text/markdown;charset=utf-8"});
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = filename();
  link.click();
  URL.revokeObjectURL(link.href);
});
